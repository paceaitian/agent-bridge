from pathlib import Path
from types import FrameType
from dataclasses import dataclass, field
from enum import StrEnum
from typing import Protocol
from contextlib import AbstractContextManager

from ..observer_dbus import ObserverView
from .pane import PaneInfo
from .process_values import ProcessInfo, DEFAULT_PROC
from .claude_roots import RootScan
from .transport_types import LocalPlatform


class Capability(StrEnum):
    VERIFIED = 'verified'
    UNVERIFIED = 'unverified'
    UNSUPPORTED = 'unsupported'


class Presence(StrEnum):
    CURRENT = 'current'
    EXITED = 'exited'
    UNKNOWN = 'unknown'


class SampleState(StrEnum):
    AVAILABLE = 'available'
    EMPTY = 'empty'  # Linux旧空表投影，不额外证明失败原因或live server
    UNAVAILABLE = 'unavailable'
    UNVERIFIED = 'unverified'


@dataclass(frozen=True)
class ProcessIdentity:
    platform: str
    pid: int
    generation_kind: str
    generation_value: str

    def stored_generation(self) -> str:
        """只编码已知种类；Linux旧字符串逐字不改，FILETIME不得裸装成ticks。"""
        if self.platform == 'linux' and self.generation_kind == 'linux-proc-ticks':
            return self.generation_value
        if (self.platform == 'windows' and self.generation_kind == 'win-filetime'
                and self.generation_value.isascii() and self.generation_value.isdecimal()):
            return 'win-filetime:' + self.generation_value
        raise ValueError('process_identity_unsupported')


@dataclass(frozen=True)
class ProcessRecord:
    identity: ProcessIdentity
    parent_pid: int
    comm: str = field(repr=False)
    tty_nr: int | None = None


@dataclass(frozen=True)
class ProcessRead:
    state: Presence
    record: ProcessRecord | None = None
    reason: str | None = None


@dataclass(frozen=True)
class ProcessSnapshot:
    state: SampleState
    records: tuple[ProcessRecord, ...] = ()


@dataclass(frozen=True)
class MuxSnapshot:
    state: SampleState
    panes: Mapping[int, PaneInfo] = field(default_factory=dict)


@dataclass(frozen=True)
class RuntimeSnapshot:
    state: SampleState
    view: ObserverView = field(default_factory=ObserverView)


class LegacyProcess(Protocol):
    def read_process(self, pid: int, proc_root: Path = DEFAULT_PROC) -> ProcessInfo | None: ...
    def ancestry(self, pid: int, proc_root: Path = DEFAULT_PROC) -> list[ProcessInfo]: ...
    def list_pids(self, proc_root: Path = DEFAULT_PROC) -> list[int]: ...
    def open_file_targets(self, pid: int, proc_root: Path = DEFAULT_PROC) -> list[str]: ...
    def open_file_scan(self, pid: int, proc_root: Path = DEFAULT_PROC) -> tuple[list[str], bool]: ...
    def launch_tokens(self, pid: int, proc_root: Path = DEFAULT_PROC) -> list[str]: ...
    def is_same_generation(self, pid: int, start_ticks: str, proc_root: Path = DEFAULT_PROC) -> bool: ...
    def pid_namespace(self, proc_root: Path = DEFAULT_PROC) -> str | None: ...
    def _argv_tokens(self, pid: int, proc_root: Path) -> tuple[list[str], bool]: ...


class ProcessBackend(Protocol):
    capability: Capability
    def read(self, pid: int) -> ProcessRead: ...
    def ancestry(self, pid: int, limit: int = 64) -> tuple[ProcessRecord, ...]: ...
    def snapshot(self) -> ProcessSnapshot: ...
    def same_generation(self, identity: ProcessIdentity) -> Presence: ...
    def generation_scan(self) -> AbstractContextManager[None]: ...
    def pid_namespace(self) -> str | None: ...
    def legacy(self) -> LegacyProcess: ...


class MuxBackend(Protocol):
    capability: Capability
    def panes(self) -> Mapping[int, PaneInfo]: ...
    def titles(self) -> Mapping[str, str]: ...
    def sample(self) -> MuxSnapshot: ...


class RuntimeProvider(Protocol):
    capability: Capability
    def sample(self) -> RuntimeSnapshot: ...
    def view(self) -> ObserverView: ...


class PathsAndIdentityBackend(Protocol):
    def state_base(self) -> Path: ...
    def state_dir(self) -> Path: ...
    def state_dir_source(self) -> str: ...
    def device_name(self) -> str: ...
    def uid(self) -> int: ...
    def codex_home(self) -> Path: ...
    def codex_sqlite_home(self) -> Path | None: ...
    def grok_home(self) -> Path: ...
    def claude_sessions_dir(self) -> Path: ...
    def claude_sessions_dirs(self, proc_root: Path = DEFAULT_PROC) -> tuple[Path, ...] | RootScan: ...
    def ensure_private_dir(self, path: Path) -> Path: ...
    def prepare_database(self, path: Path) -> None: ...
    def append_log(self, path: Path, payload: bytes, limit: int) -> None: ...
    def atomic_write(self, directory: Path, payload: bytes, *, name: str, prefix: str) -> None: ...
    def present(self, path: Path) -> bool: ...
    def policy_dir(self, provider: str) -> Path: ...
    def sqlite_uri(self, path: Path, *, escaped: bool) -> str: ...
    def root_identity(self, home: Path, sqlite_home: Path | None = None) -> str | None: ...
    def home_equal(self, reported: str, expected: Path) -> bool: ...
    def socket_identity(self, target: Path) -> tuple[str, int, int, int]: ...
    def which(self, name: str) -> str | None: ...
    def realpath(self, path: str) -> str: ...
    def mtime_ns(self, path: str) -> int: ...


class CommandResult(Protocol):
    @property
    def returncode(self) -> int: ...
    @property
    def stdout(self) -> str: ...
    @property
    def stderr(self) -> str: ...


class LockAndWorkerBackend(Protocol):
    def open_lock(self, path: Path, *, nofollow: bool = False) -> int: ...
    def try_lock(self, fd: int, *, shared: bool = False) -> None: ...
    def acquire_worker_lock(self, fd: int) -> bool: ...
    def unlock(self, fd: int) -> None: ...
    def close_lock(self, fd: int) -> None: ...
    def worker_environment(self, base: Mapping[str, str]) -> dict[str, str]: ...
    def spawn_worker(self, directory: Path, env: Mapping[str, str]) -> None: ...
    def install_stop(self, handler: Callable[[int, FrameType | None], None]) -> dict[int, object]: ...
    def restore_stop(self, previous: Mapping[int, object]) -> None: ...
    def run_capture(self, argv: Sequence[str], timeout: float, *, replace_errors: bool = False) -> CommandResult: ...


@dataclass(frozen=True)
class BridgePlatform:
    name: str
    process: ProcessBackend
    mux: MuxBackend
    runtime: RuntimeProvider
    discovery: Capability
    files: PathsAndIdentityBackend
    lifecycle: LockAndWorkerBackend
    transport: LocalPlatform
